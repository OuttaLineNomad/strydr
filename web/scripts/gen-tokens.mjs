// Generates src/styles/tokens.css from design-system/tokens.json (single source of truth).
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const src = fileURLToPath(new URL('../../design-system/tokens.json', import.meta.url))
const out = fileURLToPath(new URL('../src/styles/tokens.css', import.meta.url))
const t = JSON.parse(readFileSync(src, 'utf8'))

const light = []
const dark = []
const ref = (v) => v.replace(/^\{(.+)\}$/, 'var(--$1)')
const put = (name, value) => {
  if (typeof value === 'object') {
    light.push([name, ref(value.light)])
    dark.push([name, ref(value.dark)])
  } else {
    light.push([name, ref(value)])
  }
}
for (const c of t.color.tokens) put(c.name, c.value)
for (const s of t.shadow.tokens) put(s.name, s.value)
for (const g of [t.spacing, t.radius, t.blur]) for (const x of g.tokens) put(x.name, x.value)
for (const [k, v] of Object.entries(t.type.families)) put(`font-${k}`, v)
for (const g of t.type.groups)
  for (const s of g.styles) {
    put(`${s.name}-size`, s.fontSize)
    put(`${s.name}-leading`, s.lineHeight)
    put(`${s.name}-weight`, String(s.fontWeight))
  }
const block = (rows, indent) => rows.map(([n, v]) => `${indent}--${n}: ${v};`).join('\n')
const css = `/* GENERATED by scripts/gen-tokens.mjs from design-system/tokens.json. Do not edit. */
:root {
  color-scheme: light dark;
${block(light, '  ')}
}
@media (prefers-color-scheme: dark) {
  :root:not([data-theme='light']) {
${block(dark, '    ')}
  }
}
:root[data-theme='dark'] {
${block(dark, '  ')}
}
:root[data-theme='light'] { color-scheme: light; }
:root[data-theme='dark'] { color-scheme: dark; }
`
writeFileSync(out, css)
console.log(`tokens.css: ${light.length} light, ${dark.length} dark`)
